export function buildWhatsAppUrl(phoneDigits: string, message: string): string {
  const cleanDigits = phoneDigits.replace(/[^0-9]/g, '') || '9613399309';
  return `https://wa.me/${cleanDigits}?text=${encodeURIComponent(message)}`;
}

export function formatProductWhatsAppMessage(
  product: Product,
  storage: string,
  color: string,
  lang: Language
): string {
  const title = lang === 'ar' && product.nameAr ? product.nameAr : product.name;
  if (lang === 'ar') {
    return [
      'مرحباً CELL PHONE - Zoughaib Telecom، أود طلب هذا المنتج:',
      `• الجهاز: ${title}`,
      storage ? `• السعة: ${storage}` : '',
      color ? `• اللون: ${color}` : '',
      `• الحالة: ${product.condition === 'New' ? 'جديد' : 'مستعمل'}`,
      `• السعر: $${product.price}`,
    ]
      .filter(Boolean)
      .join('\n');
  }
  return [
    'Hello CELL PHONE - Zoughaib Telecom, I would like to order:',
    `• Product: ${title}`,
    storage ? `• Storage: ${storage}` : '',
    color ? `• Color: ${color}` : '',
    `• Condition: ${product.condition}`,
    `• Price: $${product.price}`,
  ]
    .filter(Boolean)
    .join('\n');
}

export function formatCartWhatsAppMessage(
  items: CartItem[],
  customerName: string,
  notes: string,
  lang: Language
): string {
  const total = items.reduce((sum, item) => sum + item.price * item.quantity, 0);
  if (lang === 'ar') {
    const lines = [
      'مرحباً CELL PHONE - Zoughaib Telecom، أود طلب المنتجات التالية:',
      '',
      ...items.map((item, idx) => {
        const label = item.nameAr || item.name;
        const specs = [item.storage, item.color, item.condition === 'New' ? 'جديد' : 'مستعمل']
          .filter(Boolean)
          .join(' / ');
        return `${idx + 1}. ${label} (${specs}) × ${item.quantity} — $${item.price * item.quantity}`;
      }),
      '',
      `المجموع: $${total}`,
      customerName ? `الاسم: ${customerName}` : '',
      notes ? `ملاحظات: ${notes}` : '',
    ];
    return lines.filter((l) => l !== '').join('\n');
  }

  const lines = [
    'Hello CELL PHONE - Zoughaib Telecom, here is my order:',
    '',
    ...items.map((item, idx) => {
      const specs = [item.storage, item.color, item.condition].filter(Boolean).join(' / ');
      return `${idx + 1}. ${item.name} (${specs}) × ${item.quantity} — $${item.price * item.quantity}`;
    }),
    '',
    `Total: $${total}`,
    customerName ? `Name: ${customerName}` : '',
    notes ? `Notes: ${notes}` : '',
  ];
  return lines.filter((l) => l !== '').join('\n');
}
